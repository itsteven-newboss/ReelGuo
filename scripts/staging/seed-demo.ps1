<#
.SYNOPSIS
    Loads the demo content into staging: labelled sample series, generated by ffmpeg, through the real admin pipeline.

.DESCRIPTION
    Runs scripts\seed-demo.mjs in a temporary Node container on the staging network. It generates sample clips,
    uploads them through the admin API, imports them, waits for the worker to encode them and publishes them, then adds
    sample posts and plays. Nothing is installed on this server.

    Skips when published series already exist, unless -Force is given (which adds another set).
    Every demo series and post is marked as an example and contains no real person; remove them in the admin console
    (the content and posts pages) when the reviewed content arrives.

.PARAMETER AdminPassword
    The admin password, if it was changed in the console after setup (default: REELGUO_ADMIN_PASSWORD from the settings).
#>
param(
    [int]$Series = 4,
    [int]$Episodes = 5,
    [int]$Seconds = 20,
    [switch]$Force,
    [string]$AdminPassword
)

. (Join-Path $PSScriptRoot 'common.ps1')
Test-SettingsReady

Write-Step 'Demo content'
$feed = Invoke-Http "$(Get-LocalBase)/api/v1/feed?size=1"
if ($feed.Status -ne 200) { Stop-WithError "The site is not answering ($(Get-LocalBase), HTTP $($feed.Status)). Start it first: .\scripts\staging\ops.ps1 start" }
$total = 0
try { $total = [int](($feed.Body | ConvertFrom-Json).pagination.total) } catch { $total = 0 }
if ($total -gt 0 -and -not $Force) {
    Write-Ok "skipped: $total published series already exist (use -Force to add another demo set)"
    exit 0
}

$password = $AdminPassword
if (-not $password) { $password = Get-Setting 'REELGUO_ADMIN_PASSWORD' }
$seedScript = Join-Path $RepoRoot 'scripts\seed-demo.mjs'
if (-not (Test-Path $seedScript)) { Stop-WithError "scripts\seed-demo.mjs is missing." }

Write-Note "generating and uploading $Series series x $Episodes episodes ($Seconds s each); the worker then encodes them (a few minutes)"
# The container gets ffmpeg and a Chinese font from Alpine, the seeder by docker cp (works with any Docker setup,
# no folder sharing needed), and the admin password through the environment (not on the command line).
$inner = 'apk add --no-cache ffmpeg font-noto-cjk > /dev/null && export REELGUO_FONT=$(find /usr/share/fonts -name NotoSansCJK-Regular.ttc | head -n 1) && ' +
         "node /seed-demo.mjs --api http://api:8080 --user admin --series $Series --episodes $Episodes --seconds $Seconds"
$env:REELGUO_ADMIN_PASSWORD = $password
try {
    $id = & docker create --network $Network -e REELGUO_ADMIN_PASSWORD node:24-alpine sh -c $inner
    if ($LASTEXITCODE -ne 0 -or -not $id) { Stop-WithError "Could not create the seeding container (is the network $Network there? Start staging first)." }
} finally {
    Remove-Item Env:\REELGUO_ADMIN_PASSWORD -ErrorAction SilentlyContinue
}
$id = ($id | Select-Object -Last 1).Trim()
try {
    & docker cp $seedScript "${id}:/seed-demo.mjs"
    if ($LASTEXITCODE -ne 0) { Stop-WithError 'Could not copy the seeder into its container.' }
    & docker start -a $id
    $code = $LASTEXITCODE
} finally {
    & docker rm -f $id | Out-Null
}
if ($code -ne 0) { Stop-WithError "The demo seeder stopped with exit code $code (see its output above)." }
Write-Ok 'demo content loaded and published'
