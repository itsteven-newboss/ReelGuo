// Brand images from one source picture: the 黄约短剧 mark (a transparent PNG, any size or shape). To change the icon,
// replace the source (or pass --source), run `pnpm brand:icons` and commit what it writes:
//
//   web/packages/ui/src/brand/mark-{64,128,256}.webp + mark.ts   the mark on the sites' pages (BrandMark, srcset)
//   web/apps/client/public/favicon.ico                            16, 32 and 48 px
//   web/apps/client/public/icons/icon-{192,512}.png               install icons (transparent)
//   web/apps/client/public/icons/maskable-512.png                 Android install icon (on black, inside the safe zone)
//   web/apps/client/public/icons/apple-touch-icon.png             iOS home screen (180 px, on black)
//   web/apps/admin/public/favicon.ico
//   native/boot/icon.webp, native/app-icon.png + app-icon.json    desktop / Android app (then `tauri icon`)
//
// The source is trimmed to the picture itself (transparent margins removed) and scaled with Lanczos. The page
// images are lossless WebP: pixel for pixel what was drawn, and still smaller than PNG.
//
//   node scripts/brand-icons.mjs [--source Assets/HuangyueDingDing.png] [--quality 95] [--no-native]
//     --quality N   lossy WebP at quality N (1-100) instead of lossless: smaller files, slightly softer
//     --no-native   skip the app icons (and `tauri icon`)
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const opt = (name, fallback) => { const i = args.indexOf(`--${name}`); return i >= 0 ? args[i + 1] : fallback; };
const source = resolve(repo, opt("source", "Assets/HuangyueDingDing.png"));
const quality = opt("quality") ? Number(opt("quality")) : null;
const native = !args.includes("--no-native");
if (quality !== null && !(quality >= 1 && quality <= 100)) throw new Error("--quality must be 1-100");

const webp = quality === null ? { lossless: true, effort: 6 } : { quality, alphaQuality: 100, smartSubsample: true, effort: 6 };
const clear = { r: 0, g: 0, b: 0, alpha: 0 };
const black = { r: 0, g: 0, b: 0, alpha: 1 };
const written = [];

function save(rel, data) {
  const path = join(repo, rel);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, data);
  written.push([rel, data.length]);
}

// The picture without its transparent margins.
const trimmed = await sharp(source).ensureAlpha().trim({ threshold: 1 }).png().toBuffer({ resolveWithObject: true });
const { width: srcW, height: srcH } = trimmed.info;
const aspect = srcW / srcH;
const art = trimmed.data;

const scaled = (o) => sharp(art).resize({ ...o, kernel: "lanczos3" });

// The mark placed on a square: `fill` is the share of the side its longer edge takes.
async function tile(size, fill, background = clear) {
  const box = Math.round(size * fill);
  const fit = aspect >= 1 ? { width: box } : { height: box };
  const { data, info } = await scaled(fit).png().toBuffer({ resolveWithObject: true });
  return sharp({ create: { width: size, height: size, channels: 4, background } })
    .composite([{ input: data, left: Math.round((size - info.width) / 2), top: Math.round((size - info.height) / 2) }])
    .png({ compressionLevel: 9, adaptiveFiltering: true }).toBuffer();
}

// ICO holding PNG images (every browser and Windows since Vista read these).
function ico(images) {
  const header = Buffer.alloc(6 + 16 * images.length);
  header.writeUInt16LE(0, 0); header.writeUInt16LE(1, 2); header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(({ size, png }, i) => {
    const e = 6 + 16 * i;
    header.writeUInt8(size >= 256 ? 0 : size, e); header.writeUInt8(size >= 256 ? 0 : size, e + 1);
    header.writeUInt16LE(1, e + 4); header.writeUInt16LE(32, e + 6);
    header.writeUInt32LE(png.length, e + 8); header.writeUInt32LE(offset, e + 12);
    offset += png.length;
  });
  return Buffer.concat([header, ...images.map((x) => x.png)]);
}

// 1. The mark on pages: three heights; the browser picks by displayed size and pixel density.
const files = [];
for (const h of [64, 128, 256]) {
  const { data, info } = await scaled({ height: h }).webp(webp).toBuffer({ resolveWithObject: true });
  save(`web/packages/ui/src/brand/mark-${h}.webp`, data);
  files.push({ h, w: info.width });
}
save("web/packages/ui/src/brand/mark.ts", Buffer.from(
  `// Generated by scripts/brand-icons.mjs from ${source.slice(repo.length + 1).replaceAll("\\", "/")}; don't edit, run \`pnpm brand:icons\`.\n` +
  `export const markAspect = ${(files[2].w / files[2].h).toFixed(4)}; // width / height\n` +
  `export const markFiles = [\n${files.map((f) => `  { url: new URL("./mark-${f.h}.webp", import.meta.url).href, width: ${f.w}, height: ${f.h} },`).join("\n")}\n];\n`));

// 2. Browser and install icons.
const favicon = ico(await Promise.all([16, 32, 48].map(async (size) => ({ size, png: await tile(size, 1) }))));
save("web/apps/client/public/favicon.ico", favicon);
save("web/apps/admin/public/favicon.ico", favicon);
save("web/apps/client/public/icons/icon-192.png", await tile(192, 0.94));
save("web/apps/client/public/icons/icon-512.png", await tile(512, 0.94));
// Maskable: Android may cut the icon to a circle of 80% of the side, so the whole mark stays inside it.
const safe = 0.8 / Math.sqrt(1 + (aspect >= 1 ? 1 / aspect ** 2 : aspect ** 2));
save("web/apps/client/public/icons/maskable-512.png", await tile(512, Math.min(0.9, safe * 0.96), black));
save("web/apps/client/public/icons/apple-touch-icon.png", await tile(180, 0.8, black));

// 3. The desktop / Android app: start page and the source for `tauri icon` (which writes native/src-tauri/icons).
if (native) {
  save("native/boot/icon.webp", await scaled({ height: 192 }).webp(webp).toBuffer());
  save("native/app-icon.png", await tile(1024, 0.86));
  save("native/app-icon.json", Buffer.from(JSON.stringify({ default: "app-icon.png", bg_color: "#000000", android_fg_scale: 85 }, null, 2) + "\n"));
}

console.log(`source ${source} (${srcW} x ${srcH} after trimming, ${quality === null ? "lossless" : `quality ${quality}`} WebP)`);
for (const [rel, bytes] of written) console.log(`  ${rel.padEnd(52)} ${(bytes / 1024).toFixed(1).padStart(7)} KB`);

if (native) {
  console.log("app icons: pnpm tauri icon app-icon.json (in native/) ...");
  const r = spawnSync("pnpm tauri icon app-icon.json", { cwd: join(repo, "native"), stdio: "inherit", shell: true });
  if (r.status !== 0) { console.error("tauri icon failed; run it in native/ by hand: pnpm tauri icon app-icon.json"); process.exit(1); }
}
